"""Compare smoke checkpoints to the frozen SFT and check actual adapter updates."""
import argparse
import hashlib
import json
from pathlib import Path

from .common import write_json


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--checkpoints', type=Path, required=True)
    parser.add_argument('--sft-export', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--require-sync', action='store_true')
    parser.add_argument('--steps', nargs='+', type=int, default=[1, 2])
    parser.add_argument('--first-checkpoint', type=Path,
                        help='Original global_step_1 when this smoke explicitly resumed it')
    parser.add_argument('--require-optimizer', action='store_true')
    args = parser.parse_args()
    import torch
    from safetensors import safe_open
    from safetensors.torch import load_file
    reports, previous, previous_optimizer_steps = [], None, None
    for step in args.steps:
        actor = args.checkpoints/f'global_step_{step}'/'actor'
        if step == 1 and args.first_checkpoint:
            actor = args.first_checkpoint/'actor'
        # These files are generated by this task's trusted training process.
        state = torch.load(actor/'model_world_size_1_rank_0.pt', map_location='cpu', weights_only=False, mmap=True)
        base_names = set()
        with safe_open(args.sft_export/'model.safetensors', framework='pt', device='cpu') as base:
            expected_names = set(base.keys())
            for name, value in state.items():
                if 'lora_' in name:
                    continue
                normalized = name.removeprefix('base_model.model.').replace('.base_layer.', '.')
                assert normalized in expected_names, f'Unexpected frozen tensor: {name}'
                expected = base.get_tensor(normalized).to(value.dtype)
                assert torch.equal(value, expected), f'Frozen SFT tensor changed: {name}'
                base_names.add(normalized)
            assert base_names == expected_names, 'Checkpoint is missing frozen SFT tensors'
        adapter_path = actor/'lora_adapter'
        assert (adapter_path/'adapter_config.json').is_file()
        adapter = load_file(adapter_path/'adapter_model.safetensors')
        assert adapter and all(torch.isfinite(t).all() for t in adapter.values())
        nonzero_b = sum(int(torch.count_nonzero(v)) for k, v in adapter.items() if 'lora_B' in k)
        assert nonzero_b > 0, 'LoRA B remained at its zero initialization'
        changed = None
        if previous is not None:
            assert set(previous) == set(adapter)
            changed = sum(not torch.equal(v, previous[k]) for k, v in adapter.items())
            assert changed > 0, 'Second update did not change the adapter'
        digest = hashlib.sha256()
        for name, tensor in sorted(adapter.items()):
            digest.update(name.encode())
            digest.update(str(tensor.dtype).encode())
            digest.update(tensor.contiguous().view(torch.uint8).numpy().tobytes())
        reports.append({'step': step, 'frozen_tensors_equal_to_sft': len(base_names),
                        'adapter_tensors': len(adapter), 'nonzero_lora_b_elements': nonzero_b,
                        'adapter_sha256': digest.hexdigest(),
                        'changed_since_previous_checkpoint': changed})
        if args.require_optimizer:
            optimizer = torch.load(actor/'optim_world_size_1_rank_0.pt', map_location='cpu', weights_only=False, mmap=True)
            assert optimizer['state']
            steps = set()
            for entry in optimizer['state'].values():
                steps.add(int(entry['step']))
                assert all(torch.isfinite(value).all() for value in entry.values() if torch.is_tensor(value))
            assert len(steps) == 1 and min(steps) > 0
            if previous_optimizer_steps is not None:
                assert min(steps) > previous_optimizer_steps, 'Optimizer step did not advance'
            previous_optimizer_steps = min(steps)
            reports[-1]['optimizer_steps'] = sorted(steps)
            del optimizer
        previous = adapter
        del state
    sync_verified = False
    if args.require_sync:
        paths = [args.checkpoints/'lora_loads.jsonl']
        if args.first_checkpoint:
            paths.insert(0, args.first_checkpoint.parent/'lora_loads.jsonl')
        loads = [json.loads(line) for path in paths for line in path.read_text().splitlines()]
        assert loads and all(row['loaded_values_match_cast_source'] for row in loads)
        hashes = {row['source_sha256'] for row in loads}
        assert len(hashes) >= 2, 'Rollouts did not load different policy weights'
        assert reports[0]['adapter_sha256'] in hashes, 'Step-1 checkpoint never reached the rollout loader'
        sync_verified = True
    write_json(args.output, {'checkpoint_integrity_passed': True, 'checkpoints': reports,
                            'generation_reload_verified': False,
                            'rollout_weight_sync_verified': sync_verified})
    print(reports)


if __name__ == '__main__':
    main()
